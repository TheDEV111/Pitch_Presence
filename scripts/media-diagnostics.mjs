export class MediaToolError extends Error {
  constructor(command, exitCode, stderr = '') {
    let reason = 'Check the inputs and installed codecs.';
    if (/No such filter[^\n]*drawtext/i.test(stderr))
      reason = 'The installed FFmpeg does not provide the drawtext filter.';
    else if (/Unknown encoder[^\n]*libx264/i.test(stderr))
      reason = 'The installed FFmpeg does not provide the libx264 encoder.';
    else if (/Resource temporarily unavailable|Cannot allocate memory|pthread_create/i.test(stderr))
      reason = 'The media tool could not allocate its required memory or threads.';
    else if (/No such file or directory|Cannot find a valid font/i.test(stderr))
      reason = 'A required local input or font could not be opened.';
    else if (/Invalid data found when processing input|moov atom not found/i.test(stderr))
      reason = 'The input is not a readable media file.';
    super(`${command} failed (exit ${exitCode ?? 'unknown'}). ${reason}`);
    this.name = 'MediaToolError';
    this.exitCode = exitCode;
  }
}

function safeReason(error) {
  if (error instanceof MediaToolError) return error.message;
  const message = error instanceof Error ? error.message : '';
  // Only expose messages generated by our helpers with constrained asset names.
  if (
    /^(?:ffmpeg|ffprobe) is unavailable\. Install the documented media tools\.$/.test(message) ||
    /^Invalid (?:video master name|preview URL)\.$/.test(message) ||
    /^Invalid direct video download\. Register the official MP4 URL for this licensed source\.$/.test(
      message,
    ) ||
    /^Invalid or undersized video master: [a-z-]+\.$/.test(message) ||
    /^Video master changed: [a-z-]+\. Review the asset register\.$/.test(message) ||
    /^Download the licensed [a-z-]+ master to \.media-source\/[a-z-]+\.mp4; its direct MP4 download is unavailable\. See the registered source page\.$/.test(
      message,
    ) ||
    /^Film (?:desktop|mobile) failed size\/duration acceptance\.$/.test(message)
  )
    return message;
  if (/Executable doesn't exist|browserType\.launch.*executable/i.test(message))
    return 'Chromium is unavailable. Run npx playwright install --with-deps chromium.';
  if (/ERR_CONNECTION_REFUSED|ECONNREFUSED/.test(message))
    return 'The preview server could not be reached.';
  if (/Timeout \d+ms exceeded|TimeoutError/.test(message) || error?.name === 'TimeoutError')
    return 'The browser operation timed out. Check the preview and demo scene in this stage.';
  if (/Target page, context or browser has been closed|Failed to launch.*browser/i.test(message))
    return 'Chromium could not launch or closed during capture. Check the runner dependencies.';
  if (error?.code === 'ENOENT') return 'A required local input file is missing.';
  if (error?.code === 'EACCES') return 'A required local file could not be accessed.';
  return 'Unexpected media failure. Check the inputs for this stage.';
}

export class MediaStageError extends Error {
  constructor(stage, cause) {
    super(safeReason(cause), { cause });
    this.name = 'MediaStageError';
    this.stage = stage;
  }
}

export async function mediaStep(stage, action) {
  console.log(`Media stage: ${stage}`);
  try {
    return await action();
  } catch (error) {
    if (error instanceof MediaStageError) throw error;
    throw new MediaStageError(stage, error);
  }
}

export function failureReport(error) {
  return {
    stage: error instanceof MediaStageError ? error.stage : 'Initialising the film renderer',
    message: error instanceof MediaStageError ? error.message : safeReason(error),
  };
}
